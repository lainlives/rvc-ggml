// RVC-Train-GGML - M5 training data loader (src/data/dataset.h)
//
// Role: assemble the M4 training cache (src/prep/cache.*) into the host buffers needed by a training step:
//   sample assembly (aligned with official 81eed5e train/data_utils.py::TextAudioLoaderMultiNSFsid.get_labels/
//   get_audio_text_pair): phone = repeat(feat,2) -> min(·,900) -> min-aligned with spec,
//   spec/wav/phone/pitch/pitchf truncated together; pitchf = f0 Hz after UV interpolation (no mask/scaling),
//   pitch = coarse bin (1..255, cache f0bin).
//   batch (bucket) assembly: pad to the bucket top T_b + zero x_mask/y_mask; ids_slice/q_noise/SineGen noise
//   generated by traincpp::Rng (golden replay can inject fixed values via BatchRandomInputs).
//
// Layout convention (consistent with the graph inputs of src/model/synthesizer.h and train_step_selftest.cpp; ne = reversed torch order):
//   phone  [feat_dim,T,B]   pitch [T,B] i32      pitchf [T,B] (host input)
//   spec   [T,spec_bins,B]  wave  [seg_samples,1,B] (sliced at ids*hop)
//   y_mel  [seg,n_mels,B]   q_noise [T,q_channels,B]
//   x_mask/y_mask [T,1,B]   attn_valid [T,T,1,B]  sid [B] i32
//   slice_mat [T,seg,B]     pitchf_slice [seg,B]  sine_source_slice [1,seg_samples,B]
// The training step (M5-2) builds tensors from these views; this module performs no graph/Vulkan operations (pure host).
#pragma once

#include <cstdint>
#include <map>
#include <string>
#include <vector>

#include "prep/cache.h"
#include "traincpp/traincpp.h"

namespace rvc_train {
namespace data {

// Data loading config (M5 temporary fields; finalized by the JSON config in M7)
struct TrainDataConfig {
    std::string exp_dir;             // M4 cache directory (dataset.json + samples/)
    int64_t batch_size = 1;
    int64_t segment_frames = 32;     // z frames = segment_size/hop (v1-40k = 32)
    int64_t segment_samples = 12800; // official segment_size (v1-40k = 32*400)
    int64_t q_channels = 192;        // q_noise channels (= inter_channels; v1 = 192)
    int64_t speaker_id = 0;          // single speaker fixed at 0 (official sid)
    std::vector<int64_t> buckets;    // bucket upper bounds (aligned T); the first bucket >= T is hit
    // y_mel target (official train/mel_processing.py::spec_to_mel_torch semantics)
    int64_t n_fft = 2048;
    int64_t win = 2048;
    int64_t n_mels = 125;
    double sr = 40000.0;
    double fmin = 0.0;
    double fmax = -1.0;              // <=0 means sr/2
    float log_clip = 2e-6f;          // clamp min of dynamic_range_compression
};

// Single-sample assembly result (torch layout, row-major; hop = segment_samples/segment_frames)
struct TrainSample {
    std::string id;
    int64_t frames = 0;       // aligned T
    int64_t feat_dim = 0;
    int64_t spec_bins = 0;
    int64_t hop = 0;
    std::vector<float> phone;    // [T, feat_dim] (after repeat)
    std::vector<int32_t> pitch;  // [T] (f0bin)
    std::vector<float> pitchf;   // [T] (f0hz)
    std::vector<float> spec;     // [spec_bins, T] (row-major)
    std::vector<float> wav;      // [T*hop] (truncated 0_gt)
};

// Random quantities injected by golden/cross-checks (linear layout matches the corresponding BatchBuffers fields); items not injected are generated by rng
struct BatchRandomInputs {
    std::vector<int32_t> ids_slice;  // [B]
    std::vector<float> q_noise;      // linear = [B, q_channels, T_b] (torch)
    std::vector<float> sine_noise;   // linear = [B, segment_samples] (contiguous per sample)
};

// Host buffers for one bucket batch (ne order; can be tensor_set directly into graph inputs/leaves)
struct BatchBuffers {
    int64_t frames = 0;           // T_b (bucket top)
    int64_t batch = 0;
    int64_t feat_dim = 0;
    int64_t spec_bins = 0;
    int64_t segment_frames = 0;
    int64_t segment_samples = 0;
    int64_t q_channels = 0;
    int64_t hop = 0;
    std::vector<int64_t> lengths;    // [B] valid T_i
    std::vector<int32_t> ids_slice;  // [B]
    std::vector<float> phone;        // ne [feat_dim, T_b, B]
    std::vector<int32_t> pitch;      // ne [T_b, B]
    std::vector<float> pitchf;       // ne [T_b, B] (host input)
    std::vector<float> spec;         // ne [T_b, spec_bins, B]
    std::vector<float> wave;         // ne [segment_samples, 1, B]
    std::vector<float> y_mel;        // ne [segment_frames, n_mels, B]
    std::vector<int32_t> sid;        // ne [B]
    std::vector<float> q_noise;      // ne [T_b, q_channels, B]
    std::vector<float> x_mask;       // ne [T_b, 1, B]
    std::vector<float> y_mask;       // ne [T_b, 1, B]
    std::vector<float> attn_valid;   // ne [T_b, T_b, 1, B]
    std::vector<float> slice_mat;    // ne [T_b, segment_frames, B]
    std::vector<float> pitchf_slice; // ne [segment_frames, B]
    std::vector<float> sine_source_slice;  // ne [1, segment_samples, B]
};

class Dataset {
public:
    static bool open(const std::string& cache_dir, const TrainDataConfig& cfg, Dataset* out,
                     std::string* err);

    const prep::CacheDataset& cache() const { return cache_; }
    const TrainDataConfig& config() const { return cfg_; }
    int64_t size() const { return static_cast<int64_t>(cache_.samples.size()); }
    const prep::CacheSampleInfo& sample_info(int64_t index) const;
    int64_t index_of(const std::string& id) const;  // -1 when not found

    // Official aligned frame count T (no bin reads needed; for the bucket sampler)
    int64_t aligned_frames(int64_t index) const;
    // Bucket upper bound that is hit (first >= frames); -1 when none
    int64_t bucket_of(int64_t frames) const;

    // Assemble a single sample (reads cache bin); index out of range/missing file/insufficient frames -> false + err
    bool assemble(int64_t index, TrainSample* out, std::string* err) const;
    bool assemble_id(const std::string& id, TrainSample* out, std::string* err) const;

    // Build a bucket batch:
    //   indices keep the caller's order (the official collate receives them sorted by descending length from the caller);
    //   bucket_top must be >= every sample's T_i and >= segment_frames;
    //   when injected is non-null, use the injected random values (golden replay, strict size/range validation); otherwise generate with rng.
    bool build_batch(const std::vector<int64_t>& indices, int64_t bucket_top, traincpp::Rng* rng,
                     const BatchRandomInputs* injected, BatchBuffers* out, std::string* err) const;

private:
    prep::CacheDataset cache_;
    TrainDataConfig cfg_;
    std::vector<float> mel_basis_;             // [n_mels][spec_bins] row-major
    std::map<std::string, int64_t> index_map_; // id -> samples index
};

} // namespace data
} // namespace rvc_train
